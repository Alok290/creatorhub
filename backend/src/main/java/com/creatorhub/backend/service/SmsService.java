package com.creatorhub.backend.service;

import lombok.extern.slf4j.Slf4j;
import org.springframework.beans.factory.annotation.Value;
import org.springframework.stereotype.Service;

import java.net.URI;
import java.net.URLEncoder;
import java.net.http.HttpClient;
import java.net.http.HttpRequest;
import java.net.http.HttpResponse;
import java.nio.charset.StandardCharsets;
import java.time.Duration;
import java.util.Base64;
import java.util.regex.Matcher;
import java.util.regex.Pattern;

@Service
@Slf4j
public class SmsService {

    @Value("${sms.twilio.account-sid:}")
    private String twilioAccountSid;

    @Value("${sms.twilio.auth-token:}")
    private String twilioAuthToken;

    @Value("${sms.twilio.phone-number:}")
    private String twilioPhoneNumber;

    @Value("${sms.fast2sms.api-key:}")
    private String fast2smsApiKey;

    @Value("${sms.twofactor.api-key:}")
    private String twoFactorApiKey;

    @Value("${sms.msg91.auth-key:}")
    private String msg91AuthKey;

    @Value("${sms.msg91.template-id:}")
    private String msg91TemplateId;

    private final HttpClient httpClient = HttpClient.newBuilder()
            .connectTimeout(Duration.ofSeconds(10))
            .build();

    private boolean isNotBlank(String str) {
        return str != null && !str.trim().isEmpty();
    }

    /**
     * Dispatches real SMS to a mobile phone number using configured SMS gateways.
     * Returns the active 6-digit OTP code sent in the SMS (either generated by Twilio template or fallbackOtp),
     * or null if delivery failed.
     */
    public String sendOtpSms(String phone, String fallbackOtp) {
        log.info("[SMS Service] Dispatching real carrier SMS to recipient: {}", phone);

        // 1. Check Twilio Gateway (International & Domestic)
        if (isNotBlank(twilioAccountSid) && isNotBlank(twilioAuthToken) && isNotBlank(twilioPhoneNumber)) {
            String twilioOtp = sendTwilioOtp(phone, fallbackOtp);
            if (twilioOtp != null) {
                return twilioOtp;
            }
        }

        // 2. Check Fast2SMS Gateway (India)
        if (isNotBlank(fast2smsApiKey)) {
            if (sendFast2Sms(phone, fallbackOtp)) {
                return fallbackOtp;
            }
        }

        // 3. Check 2Factor Gateway (India)
        if (isNotBlank(twoFactorApiKey)) {
            if (sendTwoFactorSms(phone, fallbackOtp)) {
                return fallbackOtp;
            }
        }

        // 4. Check MSG91 Gateway
        if (isNotBlank(msg91AuthKey)) {
            if (sendMsg91Sms(phone, fallbackOtp)) {
                return fallbackOtp;
            }
        }

        log.warn("[SMS Service] No external SMS provider credentials found or SMS dispatch failed.");
        return null;
    }

    private String sendTwilioOtp(String toPhone, String fallbackOtp) {
        try {
            String auth = Base64.getEncoder().encodeToString(
                    (twilioAccountSid.trim() + ":" + twilioAuthToken.trim()).getBytes(StandardCharsets.UTF_8)
            );
            String url = "https://api.twilio.com/2010-04-01/Accounts/" + twilioAccountSid.trim() + "/Messages.json";

            // Attempt 1: Twilio 2FA template ("sms_2fa") required for trial accounts
            String formTrial = "To=" + URLEncoder.encode(toPhone, StandardCharsets.UTF_8)
                    + "&From=" + URLEncoder.encode(twilioPhoneNumber.trim(), StandardCharsets.UTF_8)
                    + "&Body=sms_2fa";

            HttpRequest reqTrial = HttpRequest.newBuilder()
                    .uri(URI.create(url))
                    .header("Authorization", "Basic " + auth)
                    .header("Content-Type", "application/x-www-form-urlencoded")
                    .timeout(Duration.ofSeconds(10))
                    .POST(HttpRequest.BodyPublishers.ofString(formTrial))
                    .build();

            HttpResponse<String> respTrial = httpClient.send(reqTrial, HttpResponse.BodyHandlers.ofString());
            if (respTrial.statusCode() >= 200 && respTrial.statusCode() < 300) {
                log.info("[Twilio SMS] Real 2FA template SMS dispatched successfully to {}", toPhone);
                // Extract 6-digit code inserted by Twilio into the SMS body
                Matcher matcher = Pattern.compile("\\b(\\d{6})\\b").matcher(respTrial.body());
                if (matcher.find()) {
                    String twilioCode = matcher.group(1);
                    log.info("[Twilio SMS] Extracted carrier OTP code: {}", twilioCode);
                    return twilioCode;
                }
                return fallbackOtp;
            }

            // Attempt 2: Custom message body for upgraded Twilio accounts
            String customBody = "Your CreatorHub verification code is " + fallbackOtp + ". Valid for 5 minutes.";
            String formCustom = "To=" + URLEncoder.encode(toPhone, StandardCharsets.UTF_8)
                    + "&From=" + URLEncoder.encode(twilioPhoneNumber.trim(), StandardCharsets.UTF_8)
                    + "&Body=" + URLEncoder.encode(customBody, StandardCharsets.UTF_8);

            HttpRequest reqCustom = HttpRequest.newBuilder()
                    .uri(URI.create(url))
                    .header("Authorization", "Basic " + auth)
                    .header("Content-Type", "application/x-www-form-urlencoded")
                    .timeout(Duration.ofSeconds(10))
                    .POST(HttpRequest.BodyPublishers.ofString(formCustom))
                    .build();

            HttpResponse<String> respCustom = httpClient.send(reqCustom, HttpResponse.BodyHandlers.ofString());
            if (respCustom.statusCode() >= 200 && respCustom.statusCode() < 300) {
                log.info("[Twilio SMS] Real custom SMS dispatched successfully to {}", toPhone);
                return fallbackOtp;
            } else {
                log.error("[Twilio SMS] Dispatch failed. Status: {}, Body: {}", respCustom.statusCode(), respCustom.body());
                return null;
            }
        } catch (Exception e) {
            log.error("[Twilio SMS] Exception sending SMS to {}: {}", toPhone, e.getMessage());
            return null;
        }
    }

    private boolean sendFast2Sms(String toPhone, String otp) {
        try {
            String cleanedNumber = toPhone.replaceAll("[^0-9]", "");
            if (cleanedNumber.length() > 10) {
                cleanedNumber = cleanedNumber.substring(cleanedNumber.length() - 10);
            }
            String url = "https://www.fast2sms.com/dev/bulkV2?authorization=" + URLEncoder.encode(fast2smsApiKey.trim(), StandardCharsets.UTF_8)
                    + "&route=otp&variables_values=" + URLEncoder.encode(otp, StandardCharsets.UTF_8)
                    + "&numbers=" + URLEncoder.encode(cleanedNumber, StandardCharsets.UTF_8);

            HttpRequest request = HttpRequest.newBuilder()
                    .uri(URI.create(url))
                    .timeout(Duration.ofSeconds(10))
                    .GET()
                    .build();

            HttpResponse<String> response = httpClient.send(request, HttpResponse.BodyHandlers.ofString());
            if (response.statusCode() >= 200 && response.statusCode() < 300) {
                log.info("[Fast2SMS] Real OTP SMS delivered to {}", cleanedNumber);
                return true;
            } else {
                log.error("[Fast2SMS] Delivery failed. Status: {}, Body: {}", response.statusCode(), response.body());
                return false;
            }
        } catch (Exception e) {
            log.error("[Fast2SMS] Exception sending OTP to {}: {}", toPhone, e.getMessage());
            return false;
        }
    }

    private boolean sendTwoFactorSms(String toPhone, String otp) {
        try {
            String cleanedNumber = toPhone.replaceAll("[^0-9]", "");
            if (cleanedNumber.length() > 10) {
                cleanedNumber = cleanedNumber.substring(cleanedNumber.length() - 10);
            }
            String url = "https://2factor.in/API/V1/" + twoFactorApiKey.trim() + "/SMS/" + cleanedNumber + "/" + otp + "/CreatorHub";

            HttpRequest request = HttpRequest.newBuilder()
                    .uri(URI.create(url))
                    .timeout(Duration.ofSeconds(10))
                    .GET()
                    .build();

            HttpResponse<String> response = httpClient.send(request, HttpResponse.BodyHandlers.ofString());
            if (response.statusCode() >= 200 && response.statusCode() < 300) {
                log.info("[2Factor SMS] Real OTP SMS delivered to {}", cleanedNumber);
                return true;
            } else {
                log.error("[2Factor SMS] Delivery failed. Status: {}, Body: {}", response.statusCode(), response.body());
                return false;
            }
        } catch (Exception e) {
            log.error("[2Factor SMS] Exception sending OTP to {}: {}", toPhone, e.getMessage());
            return false;
        }
    }

    private boolean sendMsg91Sms(String toPhone, String otp) {
        try {
            String cleanedNumber = toPhone.replaceAll("[^0-9]", "");
            String url = "https://control.msg91.com/api/v5/otp?template_id=" + URLEncoder.encode(msg91TemplateId.trim(), StandardCharsets.UTF_8)
                    + "&mobile=" + URLEncoder.encode(cleanedNumber, StandardCharsets.UTF_8)
                    + "&authkey=" + URLEncoder.encode(msg91AuthKey.trim(), StandardCharsets.UTF_8)
                    + "&otp=" + URLEncoder.encode(otp, StandardCharsets.UTF_8);

            HttpRequest request = HttpRequest.newBuilder()
                    .uri(URI.create(url))
                    .timeout(Duration.ofSeconds(10))
                    .POST(HttpRequest.BodyPublishers.noBody())
                    .build();

            HttpResponse<String> response = httpClient.send(request, HttpResponse.BodyHandlers.ofString());
            if (response.statusCode() >= 200 && response.statusCode() < 300) {
                log.info("[MSG91 SMS] Real OTP SMS delivered to {}", cleanedNumber);
                return true;
            } else {
                log.error("[MSG91 SMS] Delivery failed. Status: {}, Body: {}", response.statusCode(), response.body());
                return false;
            }
        } catch (Exception e) {
            log.error("[MSG91 SMS] Exception sending OTP to {}: {}", toPhone, e.getMessage());
            return false;
        }
    }
}
